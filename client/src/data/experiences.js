export const getExperienceById = (id) => {
  return experiences.find(e => e.id === id) || null;
};

export const getExperiencesByDestination = (destinationId) => {
  return experiences.filter(e => e.destinationId === destinationId);
};

export const getRelatedExperiences = (id, count = 3) => {
  const exp = getExperienceById(id);
  if (!exp) return experiences.slice(0, count);
  return experiences
    .filter(e => e.id !== id && e.destinationId === exp.destinationId)
    .concat(experiences.filter(e => e.id !== id && e.destinationId !== exp.destinationId))
    .slice(0, count);
};

export default experiences;